import {test,expect} from 'playwright/test';

test.beforeEach(async({request})=>{await request.post('/__test/reset');});

test('device code survives nickname changes, reloads and role switching; settings fit desktop and phone',async({browser},testInfo)=>{
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  let registrations=0;
  page.on('request',request=>{if(request.method()==='POST'&&new URL(request.url()).pathname==='/api/v1/accounts')registrations++;});
  await page.goto('/');
  await page.getByRole('button',{name:'Maak mijn code',exact:false}).click();
  await expect(page.locator('.live-device-code')).toBeVisible();
  const code=(await page.locator('.live-device-code').innerText()).trim();
  await page.goto('/#instellingen');
  await expect(page.locator('.settings-device-code')).toContainText(code);
  for(const [name,width,height] of [['desktop',1440,1000],['mobile',390,844]]) {
    await page.setViewportSize({width,height});
    const card=page.locator('.live-settings .settings-card').first();
    const bounds=await card.boundingBox(),heading=await card.locator('h2').boundingBox(),input=await card.locator('input').boundingBox();
    expect(heading.x-bounds.x).toBeGreaterThanOrEqual(20);
    expect(heading.y-bounds.y).toBeGreaterThanOrEqual(20);
    expect(bounds.x+bounds.width-(input.x+input.width)).toBeGreaterThanOrEqual(20);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('settings-'+name+'.png'),fullPage:true});
  }
  await page.getByLabel('Naam of bijnaam',{exact:true}).fill('Robin');
  await page.getByRole('button',{name:'Opslaan',exact:true}).click();
  await expect(page.locator('#toast')).toHaveText('Je profiel is opgeslagen.');
  await page.reload();
  await expect(page.getByLabel('Naam of bijnaam',{exact:true})).toHaveValue('Robin');
  await expect(page.locator('.settings-device-code')).toContainText(code);
  await page.getByRole('button',{name:'Toon QR-code',exact:true}).click();
  await expect(page.locator('.qr-code-label')).toHaveText(code);
  await page.getByRole('button',{name:'Sluiten',exact:true}).click();
  expect(registrations).toBe(1);
  await page.getByRole('button',{name:'Wissel van profiel',exact:true}).click();
  await page.getByRole('button',{name:/Start je bedrijf Zakelijk profiel/}).click();
  await page.getByLabel('Bedrijfsnaam',{exact:true}).fill('Robin Garage');
  await page.getByRole('button',{name:'Bedrijf aanmaken',exact:true}).click();
  await page.goto('/#instellingen');
  await page.getByRole('button',{name:'Wissel van profiel',exact:true}).click();
  await page.getByRole('button',{name:/Persoonlijk Persoonlijk profiel/}).click();
  await expect(page.locator('.live-device-code')).toHaveText(code);
  expect(registrations).toBe(2); // Exactly one personal and one business profile.
  const other=await browser.newContext(),otherPage=await other.newPage();
  await otherPage.goto('/');
  await otherPage.getByRole('button',{name:'Maak mijn code',exact:false}).click();
  await expect(otherPage.locator('.live-device-code')).toBeVisible();
  expect((await otherPage.locator('.live-device-code').innerText()).trim()).not.toBe(code);
  await other.close();await context.close();
});

test('business sees and edits quick messages, retries saving, reuses edits across templates and sends edited messages',async({browser},testInfo)=>{
  const owner=await browser.newContext({viewport:{width:1200,height:1000}});
  const customer=await browser.newContext({viewport:{width:390,height:844}});
  const page=await owner.newPage(),client=await customer.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await client.goto('/');await client.getByRole('button',{name:'Maak mijn code',exact:false}).click();
  await expect(client.locator('.live-device-code')).toBeVisible();
  const code=(await client.locator('.live-device-code').innerText()).trim();
  await page.goto('/');await page.getByLabel('Bedrijfsnaam',{exact:true}).fill('Garage Eigen Tekst');
  await page.getByRole('button',{name:'Start je bedrijf',exact:false}).click();
  await page.getByRole('button',{name:'Kies bedrijfstemplate',exact:true}).click();
  await page.getByLabel('Zoek een bedrijfstemplate').fill('garage');
  await page.getByRole('button',{name:/Autogarage/}).click();
  await expect(page.locator('.quick-overview li')).toHaveCount(6);
  await page.screenshot({path:testInfo.outputPath('quick-messages-home-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:/Auto klaar.*Bewerken/}).click();
  await page.getByLabel('Knopnaam',{exact:true}).fill('Kom je auto halen');
  await page.getByLabel('Berichttitel',{exact:true}).fill('Klaar bij onze garage');
  await page.getByLabel('Berichttekst',{exact:true}).fill('Je auto staat klaar. Je kunt tot 18:00 terecht!');
  await page.route('**/api/v1/profile',route=>route.abort());
  await page.getByRole('button',{name:'Snelkeuze opslaan',exact:true}).click();
  await expect(page.locator('#quick-message-editor [data-error]')).toContainText('Geen verbinding');
  await expect(page.getByLabel('Berichttekst',{exact:true})).toHaveValue('Je auto staat klaar. Je kunt tot 18:00 terecht!');
  await page.unroute('**/api/v1/profile');
  await page.getByRole('button',{name:'Snelkeuze opslaan',exact:true}).click();
  await expect(page.locator('.quick-overview')).toContainText('Kom je auto halen');
  await page.reload();
  await expect(page.locator('.quick-overview')).toContainText('Je kunt tot 18:00 terecht!');
  await page.getByRole('button',{name:'Template wijzigen',exact:true}).click();
  await page.getByLabel('Zoek een bedrijfstemplate').fill('bloemist');
  await page.getByRole('button',{name:/Bloemist/}).click();
  await page.getByRole('button',{name:'Template wijzigen',exact:true}).click();
  await page.getByLabel('Zoek een bedrijfstemplate').fill('garage');
  await page.getByRole('button',{name:/Autogarage/}).click();
  await expect(page.locator('.quick-overview')).toContainText('Kom je auto halen');
  await page.getByRole('button',{name:/Goedkeuring vragen.*Bewerken/}).click();
  await page.getByLabel('Berichttekst',{exact:true}).fill('Kun je akkoord geven voor {details}?');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:testInfo.outputPath('quick-message-editor-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Snelkeuze opslaan',exact:true}).click();
  await page.goto('/#instellingen');
  await page.getByRole('button',{name:'Zwart (dark mode)',exact:true}).click();
  await expect(page.locator('body')).toHaveClass(/business-dark-theme/);
  await page.screenshot({path:testInfo.outputPath('settings-business-dark-mobile.png'),fullPage:true});
  await page.goto('/#home');
  await page.getByRole('button',{name:'Klant verbinden',exact:true}).click();
  await page.getByLabel('Conappt-code',{exact:true}).fill(code);
  await page.getByRole('button',{name:'Verbinden',exact:true}).click();
  await page.getByRole('button',{name:'Kom je auto halen',exact:true}).click();
  await client.getByRole('link',{name:/Garage Eigen Tekst/}).click();
  await expect(client.locator('#message-thread')).toContainText('Klaar bij onze garage');
  await expect(client.locator('#message-thread')).toContainText('Je kunt tot 18:00 terecht!');
  await page.getByRole('button',{name:'Goedkeuring vragen…',exact:true}).click();
  await expect(page.getByLabel('Bedrag in euro',{exact:true})).toHaveCount(0);
  await page.getByLabel('Wat moet er gebeuren?',{exact:true}).fill('nieuwe remmen');
  await page.getByRole('button',{name:'Bericht versturen',exact:true}).click();
  await expect(client.locator('#message-thread')).toContainText('Kun je akkoord geven voor nieuwe remmen?');
  await page.getByRole('button',{name:'Snelkeuzes aanpassen',exact:true}).click();
  await page.getByRole('button',{name:/Kom je auto halen.*Bewerken/}).click();
  await page.getByRole('button',{name:'Standaard herstellen',exact:true}).click();
  await expect(page.getByLabel('Knopnaam',{exact:true})).toHaveValue('Auto klaar');
  await page.getByRole('button',{name:'Snelkeuze opslaan',exact:true}).click();
  await expect(page.getByRole('button',{name:'Auto klaar',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:'Auto klaar',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
  await customer.close();await owner.close();
});

